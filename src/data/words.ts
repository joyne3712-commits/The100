export function getWordById(id: string): WordEntry | undefined {
  return allWords.find(w => w.id.toLowerCase() === id.toLowerCase());
}

export function getNextWord(currentId: string): WordEntry {
  const idx = allWords.findIndex(w => w.id.toLowerCase() === currentId.toLowerCase());
  if (idx === -1 || idx === allWords.length - 1) {
    return allWords[0];
  }
  return allWords[idx + 1];
}

export function getPrevWord(currentId: string): WordEntry {
  const idx = allWords.findIndex(w => w.id.toLowerCase() === currentId.toLowerCase());
  if (idx <= 0) {
    return allWords[allWords.length - 1];
  }
  return allWords[idx - 1];
}
